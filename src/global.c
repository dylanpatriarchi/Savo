int savo_line = 0;

void savo_warn(const char *fmt, ...) {
    va_list ap;
    if (savo_line > 0) fprintf(stderr, "savo: line %d: ", savo_line);
    else               fprintf(stderr, "savo: ");
    va_start(ap, fmt);
    vfprintf(stderr, fmt, ap);
    va_end(ap);
    fprintf(stderr, "\n");
}

